-- 1. Tabela de Perfis de Usuário
-- Armazena dados públicos e preferências do usuário.
-- Cria um perfil automaticamente quando um novo usuário se registra em `auth.users`.

create table profiles (
  id uuid references auth.users on delete cascade not null primary key,
  updated_at timestamp with time zone,
  nome text,
  preferencias_visuais jsonb,
  metas_diarias jsonb,
  pomodoro_config jsonb,
  notificacoes_ativas boolean,
  pausas_ativas boolean
);

alter table profiles enable row level security;
create policy "Users can view all profiles." on profiles for select using (true);
create policy "Users can insert their own profile." on profiles for insert with check (auth.uid() = id);
create policy "Users can update their own profile." on profiles for update using (auth.uid() = id);

-- Trigger para criar um perfil ao criar um novo usuário
create function public.handle_new_user()
returns trigger as $$
begin
  insert into public.profiles (id, nome, preferencias_visuais, metas_diarias, pomodoro_config, notificacoes_ativas, pausas_ativas)
  values (
    new.id,
    new.raw_user_meta_data->>'full_name',
    '{"altoContraste": false, "reducaoEstimulos": false, "textoGrande": false}',
    '{"horasSono": 8, "tarefasPrioritarias": 3, "coposAgua": 8, "pausasProgramadas": 4}',
    '{"tempoFoco": 25, "tempoPausa": 5, "tempoLongaPausa": 15, "ciclosAntesLongaPausa": 4}',
    true,
    true
  );
  return new;
end;
$$ language plpgsql security definer;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

